from pathlib import Path
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas
import re

def create_markdown_report(query: str, body: str, output_path):
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    content = f"# Market Research Report: {query}\n\n**Generated by:** CrewAI Multi-Agent Research System\n\n{body}\n"
    path.write_text(content, encoding="utf-8")
    return path

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.setFont("Helvetica", 8)
            self.setFillColor(colors.grey)
            self.drawRightString(195 * mm, 12 * mm, f"Page {self._pageNumber} of {total}")
            self.drawString(15 * mm, 12 * mm, "Market Research | Generated report")
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

def _safe_paragraph(text, style):
    escaped = (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
    return Paragraph(escaped.replace("\n", "<br/>"), style)

def create_pdf_report(query: str, body: str, output_path):
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("ReportTitle", parent=styles["Title"], textColor=colors.HexColor("#17365D"), alignment=TA_CENTER, spaceAfter=10)
    heading_style = ParagraphStyle("ReportHeading", parent=styles["Heading2"], textColor=colors.HexColor("#1F4E79"), spaceBefore=10, spaceAfter=5)
    body_style = ParagraphStyle("ReportBody", parent=styles["BodyText"], leading=14, spaceAfter=7)
    story = [
        _safe_paragraph("MARKET INTELLIGENCE REPORT", title_style),
        _safe_paragraph(query, styles["Heading2"]),
        _safe_paragraph("Generated by Multi-Agent Market Research System", styles["Italic"]),
        Spacer(1, 8)
    ]
    for raw_line in body.splitlines():
        line = raw_line.strip()
        if not line:
            story.append(Spacer(1, 4))
        elif line.startswith("#"):
            heading = re.sub(r"^#+\s*", "", line)
            story.append(_safe_paragraph(heading, heading_style))
        else:
            line = re.sub(r"^[-*]\s+", "• ", line)
            story.append(_safe_paragraph(line, body_style))
    doc = SimpleDocTemplate(str(path), pagesize=A4, rightMargin=18*mm, leftMargin=18*mm, topMargin=18*mm, bottomMargin=22*mm)
    doc.build(story, canvasmaker=NumberedCanvas)
    return path
